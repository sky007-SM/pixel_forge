    R(s, (255, 170, 60), 13, 6, 1, 2)
    R(s, (255, 170, 60), 11, 9, 2, 1)
    R(s, WHITE, 11, 10, 1, 2)
    R(s, WHITE, 12, 10, 1, 2)
    return fin(s)


