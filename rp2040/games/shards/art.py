    s = img(60, 82)
    _king(s, 1, an)
    fin(s, True, True)
    sets = []
    for ph in (2, 3):
        d = img(60, 82, True)
        _king(d, ph, an)
        d.cols[1] = OUT
        sets.append(d.cols)
    s.phase = [(s.pa, s.pw, s.pr)]
    for cols in sets:
        pa = mkpal(cols, 0)
        pw = s.pals[1]
        pr = mkpal(cols, 2)
        s.pals.append(pa)
        s.pals.append(pr)
        s.phase.append((pal_addr(pa), s.pw, pal_addr(pr)))
