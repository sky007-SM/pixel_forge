def bat(t):
    s = img(24, 14)
    WING, WING_L, BODY = (104, 66, 160), (150, 108, 205), (152, 106, 198)
    u = (0, 3, 6)[t]
    for sign in (1, -1):
        def X(x):
            return x if sign == 1 else 23 - x
        pts = [(10, 6), (5, 3), (0, 2 + u), (2, 7 + u // 3), (4, 8), (6, 10), (10, 9)]
        P(s, WING, [(X(a), b) for a, b in pts])
        LN(s, WING_L, (X(10), 6), (X(0), 2 + u))
        LN(s, WING_L, (X(9), 7), (X(3), 7 + u // 3))
    EL(s, BODY, 9, 4, 6, 8)
    P(s, BODY, [(9, 5), (9, 1), (11, 4)])
    P(s, BODY, [(15, 5), (15, 1), (13, 4)])
