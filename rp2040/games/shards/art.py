def kiro(t):
    """Kiro: 0-1 idle, 2-5 run, 6 jump, 7 fall, 8 dash, 9-10 punch, 11 slash, 12 pound, 13 hurt."""
    s = img(28, 28)
    s.ox = 6
    b = 1 if t == 1 else 0
    moving = t in (2, 3, 4, 5, 6, 7, 8)
    flt = 2 if moving else 0
    k = 2 if t in (6, 7, 8) else 0
    tip = 3 - flt
    P(s, CAPE, [(8, 10 + b), (4, 11 + b), (tip, 18 + k), (tip + 3, 22 + k), (9, 19)])
    P(s, CAPE_D, [(5, 13 + b), (tip + 1, 18 + k), (tip + 3, 21 + k), (7, 18)])
    R(s, HAIR, 4, 6 + b, 1, 5)
    R(s, GOLD, 3, 10 + b, 3, 1)
    fx, fl, bx, bl = LEGS[t]
    R(s, TUN_D, bx, 18, 3, 5 - bl)
    R(s, HAIR, bx - 1, 23 - bl, 5, 3)
    R(s, TUN, 5, 10 + b, 9, 8)
    R(s, TUN_L, 6, 10 + b, 3, 6)
    R(s, TUN_D, 12, 11 + b, 2, 7)
    R(s, GOLD, 5, 17 + b, 9, 2)
    R(s, TUN_L, 9, 12 + b, 2, 3)
    R(s, WHITE, 9, 12 + b, 1, 1)
    R(s, CAPE, 5, 9 + b, 9, 2)
    R(s, CAPE_D, max(0, 3 - flt), 11 + b, 3, 2)
    R(s, CAPE, max(0, 3 - flt), 10 + b, 3, 2)
    R(s, TUN_D, fx, 18, 3, 5 - fl)
    R(s, BOOT, fx - 1, 23 - fl, 5, 3)
    R(s, HAIR_L, fx - 1, 23 - fl, 4, 1)
    if t == 6:
        R(s, TUN_D, 12, 8 + b, 3, 4)
        R(s, SKIN, 12, 6 + b, 3, 2)
    elif t == 9:
        R(s, TUN_D, 12, 11, 4, 3)
        R(s, SKIN, 16, 11, 6, 3)
    elif t == 10:
        R(s, TUN_D, 12, 9, 4, 3)
        R(s, SKIN, 16, 7, 5, 3)
        R(s, WHITE, 21, 6, 2, 1)
    elif t == 11:
        R(s, TUN_D, 12, 11, 3, 3)
        P(s, WHITE, [(14, 10), (24, 3), (27, 6), (16, 14)])
        LN(s, TUN_L, (16, 11), (25, 5))
        R(s, GOLD, 13, 10, 2, 5)
        LN(s, WHITE, (19, 0), (26, 4))
    elif t == 13:
        R(s, TUN_D, 12, 9, 3, 4)
        R(s, SKIN, 12, 7, 3, 2)
    elif t == 12:
        R(s, TUN_D, 12, 13, 3, 5)
        R(s, TUN_L, 5, 0, 1, 5)
        R(s, TUN_L, 13, 0, 1, 5)
    else:
        R(s, TUN_D, 12, 11 + b, 3, 4)
        R(s, HAIR_L, 12, 15 + b, 3, 2)
    R(s, SKIN, 6, 3 + b, 9, 7)
    R(s, SKIN_D, 6, 9 + b, 9, 1)
    R(s, SKIN_D, 5, 6 + b, 1, 2)
    if t == 13:
        R(s, EYE, 11, 7 + b, 4, 1)
    else:
        R(s, WHITE, 11, 6 + b, 3, 3)
        R(s, EYE, 12, 6 + b, 2, 3)
        R(s, WHITE, 12, 6 + b, 1, 1)
    R(s, HAIR, 11, 5 + b, 4, 1)
    R(s, SKIN_D, 13, 9 + b, 1, 1)
    R(s, HAIR, 5, 1 + b, 10, 3)
    P(s, HAIR, [(6, 2 + b), (2, 1 + b), (1, 4 + b), (6, 5 + b)])
    P(s, HAIR, [(8, 2 + b), (10, 0), (12, 2 + b)])
